"""Converts the column-major bitmap fonts in assets/fonts-src/*.cpp into src/core/bitmapfonts.data.ts.

Format (per font): .height, .max_width, .widths (96 ASCII 32..127 + 9 extras),
.data = glyphs (max_width columns, ceil(height/8) bytes per column, big-endian, LSB = top row)
followed by 8 accents (lower shift, upper shift, then max_width one-byte columns).
"""
import json, re, sys, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
FONTS = [('font6', 'font6_data.cpp'), ('font8', 'font8_data.cpp'), ('font14_outline', 'font14_outline_data.cpp')]
EXTRAS = 'ÆÞßæþ£¥©°'
ACCENTS = ['grave', 'acute', 'circumflex', 'tilde', 'diaeresis', 'ring', 'stroke', 'cedilla']

def numbers(block):
    block = re.sub(r'//[^\n]*', '', block)
    return [int(t, 0) for t in re.findall(r'0x[0-9a-fA-F]+|\d+', block)]

out = {}
for name, fname in FONTS:
    src = (root / 'assets' / 'fonts-src' / fname).read_text(encoding='utf-8')
    height = int(re.search(r'\.height\s*=\s*(\d+)', src).group(1))
    maxw = int(re.search(r'\.max_width\s*=\s*(\d+)', src).group(1))
    widths = numbers(re.search(r'\.widths\s*=\s*\{(.*?)\}', src, re.S).group(1))
    data = numbers(re.search(r'\.data\s*=\s*\{(.*)\}\s*\}', src, re.S).group(1))
    bpc = (height + 7) // 8
    n = len(widths)
    gsize = maxw * bpc
    glyphs = []
    for g in range(n):
        raw = data[g * gsize:(g + 1) * gsize]
        cols = []
        for c in range(maxw):
            v = 0
            for b in range(bpc):
                v = (v << 8) | raw[c * bpc + b]
            cols.append(v)
        glyphs.append(cols[:max(1, widths[g])])
    rest = data[n * gsize:]
    accents = {}
    for i, a in enumerate(ACCENTS):
        chunk = rest[i * (2 + maxw):(i + 1) * (2 + maxw)]
        if len(chunk) < 2 + maxw:
            break
        accents[a] = {'lower': chunk[0], 'upper': chunk[1], 'cols': chunk[2:]}
    if len(rest) != len(ACCENTS) * (2 + maxw):
        sys.exit(f'{name}: unexpected trailing data ({len(rest)} numbers)')
    chars = {chr(32 + i): glyphs[i] for i in range(96) if 32 + i != 127}
    for i, ch in enumerate(EXTRAS):
        chars[ch] = glyphs[96 + i]
    out[name] = {'height': height, 'glyphs': chars, 'accents': accents}
    print(f'{name}: {len(chars)} glyphs, {len(accents)} accents')

ts = '// Generated by scripts/convert-bitmap-fonts.py from assets/fonts-src — do not edit by hand.\n'
ts += '// Glyphs are column bitmaps (bit 0 = top row). Accents: rows are placed at (shift - 8).\n\n'
ts += 'export interface RawBitmapFont {\n  height: number;\n  glyphs: Record<string, number[]>;\n  accents: Record<string, { lower: number; upper: number; cols: number[] }>;\n}\n\n'
ts += 'export const BITMAP_FONT_DATA: Record<string, RawBitmapFont> = ' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n'
(root / 'src' / 'core' / 'bitmapfonts.data.ts').write_text(ts, encoding='utf-8')
print('wrote src/core/bitmapfonts.data.ts')
